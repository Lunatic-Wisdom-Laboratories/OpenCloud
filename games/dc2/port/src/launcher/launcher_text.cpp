const char *Translation(Language language, std::string_view key) {
    const auto *found = std::ranges::lower_bound(kEntries, key, {}, &Entry::key);
    if (found == std::end(kEntries) || found->key != key) {
        return nullptr;
    }
    const int index = static_cast<int>(language) - 1;
    return index >= 0 && index < kLanguageCount ? found->text[index] : nullptr;
}

