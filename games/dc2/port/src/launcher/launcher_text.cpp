constexpr bool Sorted() {
    for (std::size_t i = 1; i < std::size(kEntries); ++i) {
        if (!(kEntries[i - 1].key < kEntries[i].key)) {
            return false;
        }
    }
    return true;
}
static_assert(Sorted(), "kEntries must stay sorted by key");

